"""Vault tool -- exposes multistack.Vault as an MCP tool.

Secrets management: one Vault, HA Raft by default, holding the
credentials every other capability generates. Like
Storage/SeaweedFS/Gateway/Policy/Inference/Valkey, Vault deploys into an
EXISTING cluster -- it needs a real kubeconfig_path -- and it REQUIRES
block storage too (`REQUIRES = ("cluster", "storage")`), the same as a
MinIO tenant.

SECURITY NOTE: `VaultCreateResult.admin_password`/`root_token`/
`unseal_keys` are generated by Vault itself the one time `create()`
actually initializes it -- this tool never calls `create()` (read-only,
same as every tool here), so none of those values exist yet when a plan
is rendered. Never invent one, and never claim one is available from
this tool's own result -- only the generated script, once run, produces
them."""

from __future__ import annotations

from pydantic import validate_call

from multistack import Vault

from mcp_server import mcp
from mcp_tools._script import check_script, dump, dumped_lines


def _render_script(vault: Vault) -> str:
    """Renders a validated Vault plan as the single readable Python
    script that installs it -- same reasoning as
    mcp_tools.valkey._render_script: built from the validated object's
    own fields, not a hand-typed template that could silently drop one.

    `options` (VaultOptions, carrying the chart and its HA/Raft knobs)
    renders as its own constructor call rather than a raw dict, same as
    every other capability with a nested options model here."""
    field_lines = dumped_lines(vault, dump(vault), skip=("options",))
    if vault.options is not None:
        opt_args = ", ".join(
            f"{k}={v!r}" for k, v in dump(vault.options).items())
        field_lines.append(
            f"    options={type(vault.options).__name__}({opt_args}),")

    script = (
        "from multistack import Vault, VaultOptions\n"
        "from multistack.vault import VaultBackend\n\n"
        "vault = Vault(\n" + "\n".join(field_lines) + "\n)\n"
        "backend = VaultBackend()\n"
        "result = backend.create(vault)\n"
    )
    check_script(script)
    return script


@mcp.tool()
@validate_call
def build_vault_plan(vault: Vault) -> dict:
    """
    Validate a Vault plan against the real SDK and render it as a
    single readable Python script that installs it onto an EXISTING
    cluster. Does NOT provision anything -- read-only, safe to call
    freely.

    `vault` is the real Vault type directly (requires `kubeconfig_path`
    for the cluster this installs onto). HA Raft (3 replicas) is the
    default, not opt-in -- leave `options.ha_enabled`/`options.replicas`
    alone unless the user explicitly asks for a single-pod, non-HA Vault.

    Vault REQUIRES block storage (`REQUIRES = ("cluster", "storage")`) --
    its own data sits on a PVC, exactly like a MinIO tenant. Don't
    propose it before a StorageClass exists, unless the cluster already
    has a default one.

    SECURITY: never invent, guess, or claim to have a value for
    `admin_password`, `root_token` or `unseal_keys` -- all three are
    generated by Vault itself the first time the rendered script actually
    runs `backend.create(vault)`, never by this tool (read-only, no SDK
    `create()` call happens here). If the user asks what those will be,
    say they come back on the script's own run, not from this plan.

    Once deployed, this Vault's `internal_addr` is the in-cluster URL
    another capability would use to reach it -- no token in it.

    Returns {"valid": True, ...plan..., "script": <the deployable script>}
    on success, or {"valid": False, "error": <reason>} if the SDK's own
    validation rejected it (e.g. a missing kubeconfig_path, or an even
    `replicas` count with `ha_enabled=True`).
    """
    try:
        script = _render_script(vault)
    except AssertionError as e:
        return {"valid": False, "error": str(e)}

    return {
        "valid": True,
        "kubeconfig_path": vault.kubeconfig_path,
        # resolved_namespace, not the raw field: the spec leaves
        # namespace None to mean "the implementation's default", and
        # a caller reading this back wants the one it will deploy to.
        "namespace": vault.resolved_namespace,
        "internal_addr": vault.internal_addr,
        "script": script,
    }
